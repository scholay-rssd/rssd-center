'use strict';
require('reflect-metadata');
const {test}=require('node:test'),assert=require('node:assert/strict');
const {mkdtemp,rm}=require('node:fs/promises'),{tmpdir}=require('node:os'),{join}=require('node:path');
const {createHash}=require('node:crypto');
const {Test}=require('@nestjs/testing');
const {RssdObsidianPluginController}=require('../apps/backend/dist/apps/backend/src/rssd/rssd.obsidian-plugin.controller.js');
const {publish}=require('./obsidian-plugin-releases.cjs');
const {fixture,keyPair}=require('./obsidian-plugin-releases.test.cjs');
test('public HTTP reads serve the published release and its files without credentials and cannot write',async t=>{
 const root=await mkdtemp(join(tmpdir(),'plugin-http-')),target=join(root,'releases');t.after(()=>rm(root,{recursive:true,force:true}));
 const prior=process.env.RSSD_PLUGIN_RELEASES_DIR;process.env.RSSD_PLUGIN_RELEASES_DIR=target;t.after(()=>{if(prior===undefined)delete process.env.RSSD_PLUGIN_RELEASES_DIR;else process.env.RSSD_PLUGIN_RELEASES_DIR=prior;});
 const module=await Test.createTestingModule({controllers:[RssdObsidianPluginController]}).compile();
 const app=module.createNestApplication();app.useLogger(false);await app.listen(0,'127.0.0.1');t.after(()=>app.close());const base=await app.getUrl()+'/rssd/public/v1/obsidian-plugin';
 assert.equal((await fetch(base+'/latest')).status,404);
 const release=await fixture(root,'0.2.1',{keys:keyPair()});await publish(release.dir,target,{keyFile:release.keyFile});
 const latest=await fetch(base+'/latest');assert.equal(latest.status,200);assert.equal(latest.headers.get('cache-control'),'no-store');
 assert.equal((await latest.json()).version,'0.2.1');
 const sha=createHash('sha256').update(release.main).digest('hex'),file=await fetch(base+'/files/'+sha);
 assert.equal(file.status,200);assert.equal(file.headers.get('content-type'),'application/octet-stream');assert.match(file.headers.get('cache-control'),/immutable/);
 assert.equal(file.headers.get('x-content-type-options'),'nosniff');assert.equal(file.headers.get('etag'),'"'+sha+'"');
 assert.deepEqual(Buffer.from(await file.arrayBuffer()),release.main);
 assert.equal((await fetch(base+'/files/'+sha,{headers:{'if-none-match':'"'+sha+'"'}})).status,304);
 assert.equal((await fetch(base+'/files/'+'e'.repeat(64))).status,404);
 assert.equal((await fetch(base+'/files/not-a-hash')).status,404);
 assert.equal((await fetch(base+'/latest',{method:'POST',headers:{'content-type':'application/json'},body:'{}'})).status,404);
});
